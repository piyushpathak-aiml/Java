public class IncrementDecrement {
    public static void main(String[] args) {

        // Increment and decrement operators
        // Increment means increasing the value by 1
        // Decrement means decreasing the value by 1
        // for x
        // we write x++; for increment 
        // and x--; for decrement

        // Variable declaration and assignment
        int x = 10;
        int y = 20;

        // Output 1
        System.out.println("_______________");
        System.out.println("Before increment and decrement");
        System.out.println("Value of x: " + x);
        System.out.println("Value of y: " + y);

        // increment of x

        x++;
        x++;
        x++;
        x++;

        // decrement of y

        y--;
        y--;

        // Output 2
        System.out.println("_______________");
        System.out.println("After increment and decrement");
        System.out.println("Value of x: " + x);
        System.out.println("Value of y: " + y);
    }
}