public class OrderOfOperations {
    public static void main(String[] args) {
        
        // Order of operations [P-E-M-D-A-S]
        // P = parenthesis
        // E = Exponents
        // M = Multiplications
        // D = Divisions
        // A = Additions
        // S = Subtraction

        // Variable declaration and assignment
        double result = 3 + 4 * (7 -5) / 2.0;

        // Display output
        System.out.println("Result: " + result);
    }
}