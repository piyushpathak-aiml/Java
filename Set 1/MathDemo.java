public class MathDemo {
    public static void main(String[] args) {
        
        // Some math values in the Math class.
        System.out.println(Math.PI);
        System.out.println(Math.E);
        System.out.println("____________________");

        // Commonly used Math class methods.
        double result1 = Math.pow(2, 3);
        double result2 = Math.abs(-5);
        double result3 = Math.sqrt(9);
        double result4 = Math.round(3.14);
        double result5 = Math.ceil(3.14);
        double result6 = Math.floor(3.99);
        double result7 = Math.max(10, 20);
        double result8 = Math.min(10, 20);

        // Display output
        System.out.println("____________________");
        System.out.println("The result1 is " + result1);
        System.out.println("The result2 is " + result2);
        System.out.println("The result3 is " + result3);
        System.out.println("The result4 is " + result4);
        System.out.println("The result5 is " + result5);
        System.out.println("The result6 is " + result6);
        System.out.println("The result7 is " + result7);
        System.out.println("The result8 is " + result8);  

    }
}